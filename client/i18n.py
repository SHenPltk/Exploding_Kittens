def _select(values: tuple[str, str], language: str) -> str:
    return values[0 if language == "zh" else 1]


def text(language: str, key: str, **values: object) -> str:
    return _select(TEXT[key], language).format(**values)


def card_name(language: str, card_type: str) -> str:
    return _select(CARD_NAMES.get(card_type, (card_type, card_type)), language)


def event_text(language: str, code: str) -> str:
    return _select(EVENTS.get(code, (code, code)), language)
